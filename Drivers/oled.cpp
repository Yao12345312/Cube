/**
 * @brief SPI发送一个字节
 */
void OLED_SPI_SendByte(uint8_t data)
{
    HAL_SPI_Transmit(&hspi2, &data, 1, HAL_MAX_DELAY);
}

/**
 * @brief 写命令
 */
void OLED_WriteCMD(uint8_t cmd)
{
    OLED_DC_LOW();          // 命令模式
    OLED_CS_LOW();   	// CS低
	
	osDelay(1);
    OLED_SPI_SendByte(cmd);
	
    OLED_CS_HIGH();         // CS高
	osDelay(5);
}

/**
 * @brief 写数据
 */
void OLED_WriteData(uint8_t data)
{
    OLED_DC_HIGH();         // 数据模式
    OLED_CS_LOW();         // CS低
	
	osDelay(1);
    OLED_SPI_SendByte(data);
	
    OLED_CS_HIGH();        // CS高
	osDelay(5);
}

/**
 * @brief 写多个数据
 */
void OLED_WriteDataBuffer(uint8_t *data, uint8_t count)
{
    OLED_DC_HIGH();         // 数据模式
    OLED_CS_LOW();           // CS低
	
    osDelay(1);
    for(uint8_t i = 0; i < count; i++)
    {
        OLED_SPI_SendByte(data[i]);
    }
    osDelay(1);
	
    OLED_CS_HIGH();         // CS高
}

/**
 * @brief OLED硬件初始化（GPIO和SPI）
 */
void OLED_Init_Hardware(void)
{
    // 初始化DC引脚
    HAL_GPIO_WritePin(OLED_DC_PORT, OLED_DC_PIN, GPIO_PIN_SET);
    
    // 初始化RST引脚
    HAL_GPIO_WritePin(OLED_RST_PORT, OLED_RST_PIN, GPIO_PIN_SET);
    
    // OLED上电复位
    OLED_RST_LOW();
    osDelay(100);
    OLED_RST_HIGH();
    osDelay(100);
}

/**
 * @brief OLED显示初始化
 */
void OLED_Init(void)
{
    OLED_Init_Hardware();
    
    // SSD1306初始化序列
    OLED_WriteCMD(0xAE);    // 关闭显示
    OLED_WriteCMD(0x00);    // 设置列低地址
    OLED_WriteCMD(0x10);    // 设置列高地址
    OLED_WriteCMD(0x40);    // 设置显示起始行
    OLED_WriteCMD(0x81);    // 设置对比度
    OLED_WriteCMD(0xCF);    // 对比度值
    OLED_WriteCMD(0xA1);    // 设置段重映射
    OLED_WriteCMD(0xC8);    // 设置COM扫描方向
    OLED_WriteCMD(0xA6);    // 正常显示
    OLED_WriteCMD(0xA8);    // 设置多路复用
    OLED_WriteCMD(0x3F);    // 64行
    OLED_WriteCMD(0xD3);    // 设置显示偏移
    OLED_WriteCMD(0x00);    // 偏移量为0
    OLED_WriteCMD(0xD5);    // 设置振荡器频率
    OLED_WriteCMD(0x80);    // 频率值
    OLED_WriteCMD(0xD9);    // 设置预充电周期
    OLED_WriteCMD(0xF1);    // 周期值
    OLED_WriteCMD(0xDA);    // 设置COM引脚硬件配置
    OLED_WriteCMD(0x12);    // 配置值
    OLED_WriteCMD(0xDB);    // 设置VCOMH
    OLED_WriteCMD(0x40);    // VCOMH值
    OLED_WriteCMD(0x20);    // 设置内存寻址模式
    OLED_WriteCMD(0x02);    // 页寻址模式
    OLED_WriteCMD(0x8D);    // 电荷泵设置
    OLED_WriteCMD(0x14);    // 使能电荷泵
    OLED_WriteCMD(0xA4);    // 恢复显示RAM内容
    OLED_WriteCMD(0xA6);    // 正常显示
    OLED_WriteCMD(0xAF);    // 开启显示
    
}

