DrvOLED::DrvOLED(BoardSpiPort port)
    : m_port(port), m_inited(false)
{
    s_active = this;
}

void DrvOLED::initGPIO()
{
    HW_ConfigurePinOutput(&OLED_CS_PIN,  HW_OTYPE_PUSH_PULL, GPIO_PULLUP,   GPIO_SPEED_FREQ_HIGH);
    HW_ConfigurePinOutput(&OLED_DC_PIN,  HW_OTYPE_PUSH_PULL, GPIO_NOPULL,   GPIO_SPEED_FREQ_HIGH);
    HW_ConfigurePinOutput(&OLED_RES_PIN, HW_OTYPE_PUSH_PULL, GPIO_NOPULL,   GPIO_SPEED_FREQ_HIGH);
    csHigh();
    dcHigh();
    rstHigh();
}

void DrvOLED::hardwareReset()
{
    rstLow();
    osDelay(100);
    rstHigh();
    osDelay(100);
}

// =============================================================================
// GPIO 引脚电平
// =============================================================================

void DrvOLED::csLow()  { HAL_GPIO_WritePin(HW_GpioTable[OLED_CS_PIN.port],  (uint16_t)(1u << OLED_CS_PIN.pin),  GPIO_PIN_RESET); }
void DrvOLED::csHigh() { HAL_GPIO_WritePin(HW_GpioTable[OLED_CS_PIN.port],  (uint16_t)(1u << OLED_CS_PIN.pin),  GPIO_PIN_SET); }
void DrvOLED::dcLow()  { HAL_GPIO_WritePin(HW_GpioTable[OLED_DC_PIN.port],  (uint16_t)(1u << OLED_DC_PIN.pin),  GPIO_PIN_RESET); }
void DrvOLED::dcHigh() { HAL_GPIO_WritePin(HW_GpioTable[OLED_DC_PIN.port],  (uint16_t)(1u << OLED_DC_PIN.pin),  GPIO_PIN_SET); }
void DrvOLED::rstLow() { HAL_GPIO_WritePin(HW_GpioTable[OLED_RES_PIN.port], (uint16_t)(1u << OLED_RES_PIN.pin), GPIO_PIN_RESET); }
void DrvOLED::rstHigh(){ HAL_GPIO_WritePin(HW_GpioTable[OLED_RES_PIN.port], (uint16_t)(1u << OLED_RES_PIN.pin), GPIO_PIN_SET); }

// =============================================================================
// SPI 发送 (走 board_spi_write)
// =============================================================================

void DrvOLED::spiSend(const uint8_t *data, uint16_t len)
{
    if (!data || len == 0)
        return;
    board_spi_write(m_port, data, len, -1.0);
}

// =============================================================================
// SSD1306 命令 / 数据
// =============================================================================

void DrvOLED::writeCMD(uint8_t cmd)
{
    dcLow();
    csLow();
    osDelay(1);
    spiSend(&cmd, 1);
    csHigh();
    osDelay(5);
}

void DrvOLED::writeData(uint8_t data)
{
    dcHigh();
    csLow();
    osDelay(1);
    spiSend(&data, 1);
    csHigh();
    osDelay(5);
}

void DrvOLED::writeDataBuffer(const uint8_t *data, uint8_t count)
{
    dcHigh();
    csLow();
    osDelay(1);
    spiSend(data, count);
    osDelay(1);
    csHigh();
}

void DrvOLED::initSSD1306()
{
    //SSD1306 初始化命令序列
    writeCMD(0xAE);    //关闭显示
    writeCMD(0x00);    //设置列低地址
    writeCMD(0x10);    //设置列高地址
    writeCMD(0x40);    //设置显示起始行
    writeCMD(0x81);    //设置对比度
    writeCMD(0xCF);
    writeCMD(0xA1);    //设置段映射
    writeCMD(0xC8);    //设置COM扫描方向
    writeCMD(0xA6);    //正常显示
    writeCMD(0xA8);    //设置多路复用
    writeCMD(0x3F);    //64行
    writeCMD(0xD3);    //设置显示偏移
    writeCMD(0x00);
    writeCMD(0xD5);    //设置时钟分频
    writeCMD(0x80);
    writeCMD(0xD9);    //设置预充电周期
    writeCMD(0xF1);
    writeCMD(0xDA);    //设置COM引脚硬件配置
    writeCMD(0x12);
    writeCMD(0xDB);    //设置VCOMH
    writeCMD(0x40);
    writeCMD(0x20);    //设置内存寻址模式
    writeCMD(0x02);    //页寻址模式
    writeCMD(0x8D);    //电荷泵
    writeCMD(0x14);    //使能电荷泵
    writeCMD(0xA4);    //恢复显示RAM输出
    writeCMD(0xA6);    //正常显示
    writeCMD(0xAF);    //开启显示
}

// =============================================================================
// u8g2 回调
// =============================================================================

uint8_t DrvOLED::u8x8ByteCb(u8x8_t *u8x8, uint8_t msg, uint8_t arg_int, void *arg_ptr)
{
    (void)u8x8;
    if (!s_active)
        return 0;

    switch (msg)
    {
        case U8X8_MSG_BYTE_SEND:
            //整块发送
            s_active->spiSend((const uint8_t *)arg_ptr, arg_int);
            break;

        case U8X8_MSG_BYTE_INIT:
            //SPI 已由 board 层初始化
            break;

        case U8X8_MSG_BYTE_SET_DC:
            if (arg_int) s_active->dcHigh();
            else         s_active->dcLow();
            break;

        case U8X8_MSG_BYTE_START_TRANSFER:
            s_active->csLow();
            if (u8x8->display_info->post_chip_enable_wait_ns > 0)
                u8x8->gpio_and_delay_cb(u8x8, U8X8_MSG_DELAY_NANO,
                                        u8x8->display_info->post_chip_enable_wait_ns, NULL);
            break;

        case U8X8_MSG_BYTE_END_TRANSFER:
            if (u8x8->display_info->pre_chip_disable_wait_ns > 0)
                u8x8->gpio_and_delay_cb(u8x8, U8X8_MSG_DELAY_NANO,
                                        u8x8->display_info->pre_chip_disable_wait_ns, NULL);
            s_active->csHigh();
            break;

        default:
            return 0;
    }
    return 1;
}

uint8_t DrvOLED::u8x8GpioDelayCb(u8x8_t *u8x8, uint8_t msg, uint8_t arg_int, void *arg_ptr)
{
    (void)u8x8;
    (void)arg_ptr;
    if (!s_active)
        return 0;

    switch (msg)
    {
        case U8X8_MSG_GPIO_AND_DELAY_INIT:
            break;

        case U8X8_MSG_DELAY_MILLI:
            osDelay(arg_int);
            break;

        case U8X8_MSG_GPIO_CS:
            if (arg_int) s_active->csHigh();
            else         s_active->csLow();
            break;

        case U8X8_MSG_GPIO_DC:
            if (arg_int) s_active->dcHigh();
            else         s_active->dcLow();
            break;

        case U8X8_MSG_GPIO_RESET:
            if (arg_int) s_active->rstHigh();
            else         s_active->rstLow();
            break;

        default:
            return 0;
    }
    return 1;
}

// =============================================================================
// 初始化
// =============================================================================

bool DrvOLED::init()
{
    if (m_inited)
        return true;

    if (m_port == BOARD_SPI_NONE)
        return false;

    s_active = this;

    initGPIO();
    hardwareReset();

    //u8g2 建屏 (SSD1306 128x64 全缓冲, SPI 接口)
    u8g2_Setup_ssd1315_128x64_noname_f(&m_u8g2, U8G2_R0, u8x8ByteCb, u8x8GpioDelayCb);
    u8g2_InitDisplay(&m_u8g2);          //u8g2 内部发送 SSD1306 初始化命令
    u8g2_SetPowerSave(&m_u8g2, 0);      //开启显示
    u8g2_SetDisplayRotation(&m_u8g2, U8G2_R0);
    u8g2_ClearBuffer(&m_u8g2);

    m_inited = true;
    return true;
}

