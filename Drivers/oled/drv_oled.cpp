void DrvOLED::clear()       { u8g2_ClearBuffer(&m_u8g2); }
void DrvOLED::update()      { u8g2_SendBuffer(&m_u8g2); }

void DrvOLED::showString(uint8_t x, uint8_t y, const char *str)
{
    u8g2_SetFont(&m_u8g2, u8g2_font_ncenB10_tr);
    u8g2_DrawStr(&m_u8g2, x, y + 16, str);
}

void DrvOLED::showImage(uint8_t x, uint8_t y, uint8_t width, uint8_t height, const uint8_t *image)
{
    u8g2_DrawXBMP(&m_u8g2, x, y, width, height, image);
}

void DrvOLED::drawPixel(uint8_t x, uint8_t y)
{
    u8g2_DrawPixel(&m_u8g2, x, y);
}

void DrvOLED::drawLine(int16_t x0, int16_t y0, int16_t x1, int16_t y1)
{
    u8g2_DrawLine(&m_u8g2, x0, y0, x1, y1);
}

void DrvOLED::drawCircle(int16_t x, int16_t y, uint8_t radius, uint8_t is_filled)
{
    if (is_filled)
        u8g2_DrawDisc(&m_u8g2, x, y, radius, U8G2_DRAW_ALL);
    else
        u8g2_DrawCircle(&m_u8g2, x, y, radius, U8G2_DRAW_ALL);
}

void DrvOLED::drawRectangle(int16_t x, int16_t y, uint8_t width, uint8_t height, uint8_t is_filled)
{
    if (is_filled)
        u8g2_DrawBox(&m_u8g2, x, y, width, height);
    else
        u8g2_DrawFrame(&m_u8g2, x, y, width, height);
}

void DrvOLED::showChinese(int16_t x, int16_t y, const char *chinese)
{
    u8g2_SetFont(&m_u8g2, u8g2_font_wqy12_t_gb2312b);
    u8g2_DrawUTF8(&m_u8g2, x + 2, y + 12, chinese);
}

void DrvOLED::showFloat(uint8_t x, uint8_t y, float num)
{
    char buf[20];
    int32_t temp = (int32_t)(num * 10000);
    int32_t int_part = temp / 10000;
    int32_t frac_part = temp % 10000;
    if (frac_part < 0) frac_part = -frac_part;
    sprintf(buf, "%ld.%04ld", (long)int_part, (long)frac_part);
    showString(x, y, buf);
}

