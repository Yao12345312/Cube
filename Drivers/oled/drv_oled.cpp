//   第2步屏幕全亮                  → 硬件 OK, 问题在 u8g2 中间件集成
//
void DrvOLED::debugTest(uint8_t step)
{
    if (m_port == BOARD_SPI_NONE)
        return;

    s_active = this;
    initGPIO();   //确保 GPIO 已配置 (可重复调用)

    //------------- 第1步: GPIO 翻转测试 (万用表验证) -------------
    if (step == 1)
    {
        //RES: 拉低 2 秒(屏幕会复位变黑), 再拉高
        rstLow();  osDelay(2000);
        rstHigh(); osDelay(2000);
        //DC 翻转
        dcLow();   osDelay(1000);
        dcHigh();  osDelay(1000);
        //CS 翻转
        csLow();   osDelay(1000);
        csHigh();  osDelay(1000);
        return;
    }

    //------------- 第2步: 原始 SSD1306 命令, 全屏点亮 -------------
    if (step == 2)
    {
        //硬件复位
        rstLow();  osDelay(50);
        rstHigh(); osDelay(100);

        //最简初始化序列 (不依赖 u8g2)
        writeCMD(0xAE);              //display off
        writeCMD(0x20); writeCMD(0x00); //horizontal addressing mode
        writeCMD(0x21); writeCMD(0x00); writeCMD(0x7F); //col 0~127
        writeCMD(0x22); writeCMD(0x00); writeCMD(0x07); //page 0~7
        writeCMD(0x8D); writeCMD(0x14); //charge pump on
        writeCMD(0xAF);              //display on

        //连续写 128*8 = 1024 字节 0xFF, 点亮全部像素
        //(若屏幕亮起白屏 → SPI/GPIO/复位 全部正常, 问题在 u8g2 集成)
        csLow();
        dcHigh();   //数据模式
        static uint8_t fill[16];
        memset(fill, 0xFF, sizeof(fill));
        for (int i = 0; i < 64; i++)   //64 * 16 = 1024
            spiSend(fill, 16);
        csHigh();
        return;
    }
}

